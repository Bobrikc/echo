package com.echocity.velmar;

import static com.echocity.velmar.StoryData.n;

/** Сюжет: шайка Брока (переулок) и Мира (воры). */
final class StoryStreet {
    private StoryStreet() {}

    static void register() {
        brok();
        thugs();
        mira();
    }

    private static void brok() {
        n("brok_intro", "Брок",
            "Стоять, чужак. Проход по этому переулку платный: кошель или зубы. Хват и Ржавый уже разминаются. Выбирай.")
            .set("gang_met")
            .go("Отдать монеты.", "brok_pay")
            .go("Драться.", "brok_fight")
            .go("Убежать.", "brok_run")
            .go("Позвать стражу.", "brok_guard")
            .goIf("heard_brok", "[Эхо] «Тебе заплатил человек в красном. Ты боишься Миру».", "brok_echo");

        n("brok_pay", "Брок",
            "Брок пересчитывает монеты и ухмыляется: «Умный. Хват, пропусти его».\n"
          + "«Раз такой умный, скажу: наша хозяйка Мира любит умных. Днём сидит в лачуге на востоке, вечером выходит к рынку, ночью возвращается в переулок».")
            .set("gang_paid", "know_mira")
            .go("Понятно.", "brok_hub");

        n("brok_fight", "Брок",
            "Ты замахиваешься первым, и Ржавый бьёт под рёбра. Мир кружится, но ты держишься на ногах. Брок хохочет:\n"
          + "«Хорош! Ладно, чужак, уважаю. Нас наняли припугнуть тех, кто роет про книгу: человек в красном. А Мира — на востоке, ищи её».")
            .hurt(6).set("gang_fight", "know_mira", "brok_hint_red")
            .go("Понятно.", "brok_hub");

        n("brok_run", "Брок",
            "Ты бросаешься прочь. За спиной свист и хохот, камень пролетает над ухом. «Беги-беги!» — кричит Хват.\n"
          + "Мира это запомнит.")
            .set("gang_run");

        n("brok_guard", "Брок",
            "Ты кричишь: «Стража!» Через миг на улице гремят сапоги: Гарт хватает Брока за шиворот. «Опять ты». Хват и Ржавый растворяются в переулках.\n"
          + "Гарт отпускает Брока под честное слово и кивает тебе: «Ты поступил по закону. Я запомню».")
            .set("gang_guard", "know_mira", "garth_ok")
            .go("Понятно.", "brok_hub");

        n("brok_echo", "Брок",
            "Брок бледнеет. «Ты... слышишь?! Ладно, ладно! Мне заплатил человек в красном, не знаю за что. Мира узнает — убьёт. Помоги мне, а я скажу, где она».")
            .set("brok_truth", "know_mira", "brok_hint_red")
            .go("Говори.", "brok_mira");

        n("brok_hub", "Брок", "Чего тебе?")
            .also("gang_run", "А, это ты убегал? Ха-ха.")
            .also("gang_fight", "Ты нормально дерёшься, чужак.")
            .also("gang_guard", "Стражу позвал... ну да, ладно.")
            .goIf("know_mira", "Где найти Миру?", "brok_mira")
            .goIf("brok_hint_red", "Кто тебе платил?", "brok_red")
            .goUnless("know_mira", "Извини, что убежал. Где Мира?", "brok_apology")
            .go("Ладно, пойду.", "brok_bye");

        n("brok_mira", "Брок",
            "Днём она в лачуге за переулком, вечером приходит к рынку, ночью возвращается в переулок. Скажешь, что от меня, не сожжёт сразу.")
            .go("Понятно.", "brok_hub");

        n("brok_apology", "Брок",
            "Ха! Ладно, трусы тоже полезны. Мира — в лачуге на востоке днём, ночью в переулке. Не говори, что от меня.")
            .set("know_mira")
            .go("Понятно.", "brok_hub");

        n("brok_red", "Брок",
            "Красная накидка с золотыми пуговицами. Говорил как хозяин, не как вор. Больше ничего не знаю.")
            .go("Понятно.", "brok_hub");

        n("brok_bye", "Брок", "Давай, давай, не маячь.");

        n("brok_after", "Брок", "Мы теперь носим мешки. Не так уж плохо.")
            .also("ending_law", "Правда, теперь за мной ходит страж. Но ем я каждый день.")
            .also("ending_street", "Мы сыты. Мира заняла гильдию, а я стал ей правой рукой.")
            .also("ending_silence", "Когда звонил колокол, я услышал свои собственные мысли. Больше я не воровал.");
    }

    private static void thugs() {
        n("thug_hvat", "Хват", "Я Хват. Скажет босс бить — буду бить. Скажет носить — понесу.")
            .also("gang_fight", "Ты, говорят, хорошо дерёшься. Уважаю.")
            .also("gang_run", "А, это ты бегал! Ха-ха-ха!")
            .also("gang_guard", "Это из-за тебя Гарт трогал Брока. Не прощу.");

        n("thug_rzhavy", "Ржавый", "Хозяйка велела не трогать тех, кто с раковиной. Не спрашивай почему, спроси у неё.")
            .also("gang_run", "А ты быстро бегаешь, чужак.");
    }

    private static void mira() {
        n("mira_intro", "Мира",
            "Из тени выходит женщина с прищуренным взглядом. «Значит, ты тот самый чужак с раковиной. Говорят, ты слышишь мысли. Забавно: я тоже слышу. Шаги, шорохи, ложь».")
            .set("mira_met")
            .also("gang_run", "Это ты бегал от моих ребят? Хм.")
            .also("gang_fight", "Ты дрался с Броком. Он любит так проверять людей.")
            .also("gang_paid", "Заплатил за проход? Умно.")
            .also("gang_guard", "Стражу звал, говорят. Не люблю предателей... но Брока ты не бросил.")
            .go("Это ты украла книгу?", "mira_book")
            .go("Что тебе нужно?", "mira_need")
            .goIf("heard_mira", "[Эхо] «Ты украла книгу, чтобы кормить квартал».", "mira_echo")
            .go("Пойду.", "mira_bye");

        n("mira_hub", "Мира", "Говори. Только быстро.")
            .go("Это ты украла книгу?", "mira_book")
            .go("Что тебе нужно?", "mira_need")
            .goWhen("heard_mira", "has_ledger", "[Эхо] «Ты украла книгу, чтобы кормить квартал».", "mira_echo")
            .goWhen("gang_fight", "has_ledger", "Дай мне книгу. Я дрался с Броком, он за меня поручится.", "mira_fight_book")
            .goWhen("mira_deal,tower_clue,mira_trust", "", "Начнём штурм башни.", "mira_raid")
            .go("Пойду.", "mira_bye");

        n("mira_book", "Мира",
            "Да, книга у меня. В ней цифры: сколько зерна на самом деле лежит в башне. Но я не отдам её тому, кого не знаю.\n"
          + "Докажи, что ты не человек Орсена.")
            .also("orsen_job", "Ты работаешь на Орсена? Тогда не жди от меня добра.")
            .go("Понятно.", "mira_hub");

        n("mira_need", "Мира",
            "Хлеб для моего квартала. Башню вскроем ночью с моими ребятами, хлеб раздадим. Но мне нужен человек, который знает слабое место башни. Нуна знает больше, чем говорит.")
            .go("Я с тобой.", "mira_deal")
            .go("Мне нужно подумать.", "mira_hub");

        n("mira_deal", "Мира", "Хорошо. Тогда запомни: на башню идём ночью. Слово дал — не отступай.\nНо сначала мне нужно тебе поверить. Докажи делом или правдой.")
            .set("mira_deal")
            .go("Понятно.", "mira_hub");

        n("mira_echo", "Мира",
            "Мира долго молчит. «Значит, ты слышал. Тогда ты знаешь: я не врала ни разу. Бери книгу».\n"
          + "Она протягивает тяжёлую книгу в чёрной коже.")
            .set("has_ledger", "mira_trust")
            .go("Понятно.", "mira_hub");

        n("mira_fight_book", "Мира",
            "Брок говорил про тебя: мало слов, много дела. Бери. Книга острая, как нож: береги пальцы.")
            .set("has_ledger", "mira_trust")
            .go("Понятно.", "mira_hub");

        n("mira_raid", "Рассказчик",
            "Ночью вы идёте к башне. Брок сбивает замок, Хват и Ржавый тащат мешки, а Мира раздаёт хлеб в квартале. Орсен бежит из города под крики.\n"
          + "К рассвету у Вельмара больше нет закона: Гарт заперся в казармах, Мира заняла гильдию. Сытые улицы шумят до самого утра.\n"
          + "Раковина в твоей руке поёт тише. Теперь Вельмар слышит только силу.")
            .set("finished", "ending_street")
            .end("Хлеб улицы", "Башню вскрыли, а город раскололся");

        n("mira_bye", "Мира", "Ищи меня там, где темно.");

        n("mira_after", "Мира", "Мы сыты. Остальное — цена.")
            .also("ending_law", "Гарт вывел Орсена. Я иду под суд, но свободнее, чем раньше.")
            .also("ending_silence", "Колокол сказал вслух то, что я боялась крикнуть.");
    }
}
